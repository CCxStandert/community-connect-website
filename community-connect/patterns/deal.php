<div id="agreement" class="wp-block-group agree max"><!-- wp:details {"anchor":"ag-why-we-do-this"} -->
<details class="wp-block-details" id="ag-why-we-do-this"><summary>Why we do this</summary><!-- wp:paragraph -->
<p>Community Connect is a non-profit bike collective in Cape Town. Together with Standert we keep a small fleet of premium gravel and road bikes that <strong>anyone can borrow</strong>. You don't have to be fast, famous or part of the crew. We do our best to keep the bikes available as often as we can, so more people get to ride.</p>
<!-- /wp:paragraph --><!-- wp:paragraph -->
<p>The whole idea is simple: <strong>share the joy of riding a really good bike, and meet people who love it as much as you do.</strong> If you end up riding with the person who handed you the bike, even better.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details --><!-- wp:details {"anchor":"ag-before-you-ride"} -->
<details class="wp-block-details" id="ag-before-you-ride"><summary>Before you ride</summary><!-- wp:list -->
<ul class="wp-block-list"><!-- wp:list-item -->
<li><strong>Request the bike on our website.</strong> You can ask for any dates up to the end of next year (right now: 31 December 2027). We check the calendar and confirm by email, usually within a couple of days.</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li><strong>Loans are usually up to 7 days.</strong> That keeps the bikes moving, so more people get to ride them. Need one longer, for a multi-day race, a bikepacking trip or a project? Tell us why in your request: we make exceptions when there's a need.</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li><strong>We always keep one day free between loans.</strong> That's our day to check the bike and pass it on calmly, so please don't ask us to squeeze bookings back to back.</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li><strong>Handoffs happen on WhatsApp.</strong> We'll put you in a chat with the rider before or after you, or with the crew, to agree a time and place.</li>
<!-- /wp:list-item --></ul>
<!-- /wp:list --></details>
<!-- /wp:details --><!-- wp:details {"anchor":"ag-handing-over"} -->
<details class="wp-block-details" id="ag-handing-over"><summary>Handing over between riders</summary><!-- wp:paragraph -->
<p>When you collect a bike from the rider before you, <strong>check it together</strong>. Look at the tyres, brakes, gears, frame and wheels, and that everything's there. If anything isn't in decent shape, <strong>tell us in the WhatsApp chat right then</strong>, ideally with a photo. Whatever isn't mentioned at the handover, we assume you received in good condition.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details --><!-- wp:details {"anchor":"ag-while-you-have-it"} -->
<details class="wp-block-details" id="ag-while-you-have-it"><summary>While you have it</summary><!-- wp:list -->
<ul class="wp-block-list"><!-- wp:list-item -->
<li><strong>Treat it like your own.</strong> It's not meant as an everyday ride: take it on the rides that make it worth borrowing.</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li><strong>Something feels off? Tell us early.</strong> A strange noise, a wobbly wheel, a scratch you're not sure about: message us. Small things caught early stay small.</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li><strong>Same condition back.</strong> Clean, chain lubed, everything still on it.</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li><strong>Back on time.</strong> Someone else is usually waiting for the bike. Need more time? Ask us before your end date and we'll see what we can do.</li>
<!-- /wp:list-item --></ul>
<!-- /wp:list --></details>
<!-- /wp:details --><!-- wp:details {"anchor":"ag-events"} -->
<details class="wp-block-details" id="ag-events"><summary>Races, rides and raffles</summary><!-- wp:paragraph -->
<p>Taking a bike to an event, from a social ride to an overnight bikepacking trip or a race? Brilliant, tell us which one when you ask. <strong>Racing is harder on a bike than riding</strong>, so for races there's one extra box to tick: <strong>damage that happens while racing, crashes included, is yours to cover.</strong> Everything else stays the same.</p>
<!-- /wp:paragraph --><!-- wp:paragraph -->
<p>Some events run raffles with us: the winner gets a bike for the event, and sometimes the entry, nutrition or kit too. <strong>We hold those bikes back until the winner is drawn</strong>, sometimes right before the event; they show as raffle bikes in the calendar. If a raffle bike isn't claimed, it goes back into the pool and you can ask for it.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details --><!-- wp:details {"anchor":"ag-share"} -->
<details class="wp-block-details" id="ag-share"><summary>Share what the bike let you do</summary><!-- wp:paragraph -->
<p>We love photos, short videos, a GPX file, a few lines about where you went, who you met or what you finally dared to ride. Tag <strong>@cc_x_standert</strong> or send it to us. It helps us show what this project makes possible. You don't need to tell us how great the bike rides: we care much more about the ride, the place and the people.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details --><!-- wp:details {"anchor":"ag-your-details"} -->
<details class="wp-block-details" id="ag-your-details"><summary>Your details</summary><!-- wp:paragraph -->
<p>We keep your name, email, WhatsApp number, height (and your weight if you give it, for the tyre pressure) and your loan history, so we can arrange this loan and future ones. We don't sell or share them. Ask us anytime to see or delete them.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details --><!-- wp:details {"anchor":"ag-in-short"} -->
<details class="wp-block-details" id="ag-in-short"><summary>In short</summary><!-- wp:paragraph -->
<p>Ride it, enjoy it, look after it, bring it back clean, and tell us what you got up to. Then pass it on. <strong>Ride hard, look after it, pass it on.</strong></p>
<!-- /wp:paragraph --><!-- wp:paragraph -->
<p><em>Questions? Reply to any of our emails or message us on WhatsApp.</em></p>
